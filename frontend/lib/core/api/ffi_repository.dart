  /// Called once at startup to create the user finances record if absent.
  /// The db is already open at this point (done in main.dart via initDb).
  Future<void> init() async {
    try {
      await initFinances();
    } catch (e) {
      // FinancesNotFound means it was already initialised — ignore.
      if (!e.toString().contains('already')) _throw(e);
    }
  }

  // ── Queries ────────────────────────────────────────────────────────────────

  Future<List<AccountSummary>> listAccounts() async {
    try {
      final results = await listAccounts();
      return results.map((r) => AccountSummary(
        accountId:   r.accountId,
        accountName: r.accountName,
        accountType: r.accountType,
        currency:    r.currency,
        balance:     r.balance,
        isDebt:      r.isDebt,
        isOverdue:   r.isOverdue,
      )).toList();
    } catch (e) { _throw(e); }
  }

  Future<List<NetWorthResult>> getNetWorth({String? currency}) async {
    try {
