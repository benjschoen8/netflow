  Future<List<LedgerEntry>> statementEntries(
      String accountId, String statementId) async {
    // The FFI layer doesn't have a dedicated statement-entries function —
    // it returns all entries and the caller filters by date range, exactly
    // as the HTTP statement_entries handler does internally.
    // We fetch all entries and filter client-side using the statement dates.
    try {
      final stmts = await listStatements(accountId: accountId);
      final stmt  = stmts.firstWhere(
        (s) => s.id == statementId,
        orElse: () => throw 'Statement $statementId not found',
      );
      final all = await listEntries(accountId: accountId);
      final start = DateTime.parse(stmt.cycleStart);
      final end   = DateTime.parse(stmt.cycleEnd)
                        .add(const Duration(hours: 23, minutes: 59, seconds: 59));
      return all.where((e) {
        final t = DateTime.parse(e.occurredAt);
        return t.isAfter(start.subtract(const Duration(seconds: 1))) &&
               t.isBefore(end.add(const Duration(seconds: 1)));
      }).toList();
    } catch (e) { _throw(e); }
  }

