/// FFI-backed repository — drop-in replacement for the HTTP LedgerRepository.
///
/// Instead of making HTTP requests, every method calls the generated Dart
/// bindings that talk directly to the compiled Rust library.
///
/// The generated functions live in lib/src/rust/frb_generated.dart and are
/// produced by running:
///
///   dart run flutter_rust_bridge_codegen generate
///
/// Naming convention (flutter_rust_bridge v2):
///   Rust  fn list_accounts()  →  Dart  listAccounts()
///   Rust  fn open_cash_account(name, ..)  →  Dart  openCashAccount(name: ..)
///
/// All generated functions are top-level async Dart functions that return
/// the same primitive-struct DTOs defined in ledger::interface::ffi.
/// We map those onto the existing Dart model classes so nothing else in the
/// app needs to change.

