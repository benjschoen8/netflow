// ── Error handling ────────────────────────────────────────────────────────────

/// Matches ApiException so the rest of the app doesn't need to change.
class ApiException implements Exception {
  final int statusCode;
  final String message;
  const ApiException(this.statusCode, this.message);

  bool get isNotFound => message.contains('not found') || message.contains('NotFound');

  @override
  String toString() => 'FfiException: $message';
}

/// Wraps a Rust Result<T, String> — the FFI functions return either a value
/// or throw a String error. We convert that into ApiException.
T _unwrap<T>(T value) => value; // generated fns throw on Err automatically

/// Rust errors come back as thrown Strings from the generated bindings.
/// We catch them and wrap in ApiException so existing error-handling works.
Never _throw(Object err) =>
    throw ApiException(500, err.toString());

