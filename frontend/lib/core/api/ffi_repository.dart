      return results.map((r) => NetWorthResult(
        currency:     r.currency,
        totalAssets:  r.totalAssets,
        totalDebts:   r.totalDebts,
        netWorth:     r.netWorth,
        isDeficit:    r.isDeficit,
      )).toList();
    } catch (e) { _throw(e); }
  }

